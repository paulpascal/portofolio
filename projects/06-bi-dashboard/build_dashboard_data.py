"""
Stage 06 - BI dashboard data.

Lifecycle: dashboards, reporting
Architecture: business intelligence layer reading the marts (no backend; the
              dashboard is a static page so it can live on GitHub Pages)

Reads the country-month mart (and the upstream quality + model reports if present)
and writes a small data.js the static dashboard renders with Chart.js.

Run (after 03-transformations-marts/build_marts.py):
    python build_dashboard_data.py
Output:
    data.js   (next to index.html)
"""
import json
from pathlib import Path
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
MARTS = ROOT / "_shared" / "data" / "marts"
HERE = Path(__file__).resolve().parent

m = pd.read_parquet(MARTS / "mart_country_month.parquet")

by_country = (m.groupby("country")["households_visited"].sum()
              .sort_values(ascending=False))
attain = (m.groupby("country")["avg_attainment"].mean()
          .reindex(by_country.index))
monthly = m.groupby("period")["households_visited"].sum().sort_index()
below = (m.groupby("country")["pct_sites_below_target"].mean()
         .sort_values(ascending=False))

data = {
    "households_by_country": {"labels": by_country.index.tolist(),
                              "values": [int(v) for v in by_country.values]},
    "attainment_by_country": {"labels": attain.index.tolist(),
                              "values": [round(float(v), 3) for v in attain.values]},
    "monthly_households": {"labels": monthly.index.tolist(),
                           "values": [int(v) for v in monthly.values]},
    "below_target_by_country": {"labels": below.index.tolist(),
                                "values": [round(float(v), 1) for v in below.values]},
}

# fold in upstream quality + model headline numbers if available
q = ROOT / "02-cleaning-quality" / "quality_report.json"
mdl = ROOT / "05-prediction" / "model_report.json"
if q.exists():
    data["quality"] = json.loads(q.read_text())
if mdl.exists():
    data["model"] = json.loads(mdl.read_text())

with open(HERE / "data.js", "w") as f:
    f.write("// Auto-generated by build_dashboard_data.py. Data is SYNTHETIC.\n")
    f.write("const DATA = " + json.dumps(data, indent=2) + ";\n")

print("Wrote data.js for the dashboard.")
